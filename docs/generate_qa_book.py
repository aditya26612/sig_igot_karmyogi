def heading(text, level):
    style = S["h1"] if level == 0 else S["h2"]
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def _as_list(x):
    if x is None:
        return []
    return x if isinstance(x, list) else [x]

def h1_block(text, first_flowable=None):
    """H1 with accent underline; orphan-protected; keeps rule + first content."""
    parts = [heading(text, 0),
             HRFlowable(width="100%", thickness=1.4, color=ACCENT,
                        spaceBefore=0, spaceAfter=9)]
    parts.extend(_as_list(first_flowable))
    return [CondPageBreak(PAGE_H * 0.15), KeepTogether(parts)]

def h2_block(text, first_flowable=None):
    parts = [heading(text, 1)]
    parts.extend(_as_list(first_flowable))
    return [KeepTogether(parts)] if first_flowable else [heading(text, 1)]

