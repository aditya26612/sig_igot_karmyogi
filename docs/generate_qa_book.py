def styled_table(headers, rows, ratios, caption=None, center_cols=None):
    center_cols = center_cols or []
    col_w = [r * AVAIL for r in ratios]
    data = [[Paragraph("<b>%s</b>" % h, S["th"]) for h in headers]]
    for r in rows:
        row = []
        for i, cell in enumerate(r):
            row.append(Paragraph(cell, S["td_c"] if i in center_cols else S["td"]))
        data.append(row)
    t = Table(data, colWidths=col_w, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_STRIPE if i % 2 == 0 else colors.white))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 6), t]
    if caption:
        out.append(Paragraph(caption, S["caption"]))
    out.append(Spacer(1, 4))
    return out

